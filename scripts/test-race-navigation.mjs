import assert from 'node:assert/strict'
import fs from 'node:fs'

const desktop = fs.readFileSync(new URL('../_layouts/default.html', import.meta.url), 'utf8')
const mobile = fs.readFileSync(new URL('../_includes/header.html', import.meta.url), 'utf8')
const footer = fs.readFileSync(new URL('../_includes/footer.html', import.meta.url), 'utf8')
const page = fs.readFileSync(new URL('../corridas.md', import.meta.url), 'utf8')
const details = fs.readFileSync(new URL('../corridas-detalhes.md', import.meta.url), 'utf8')
const detailCard = fs.readFileSync(new URL('../_includes/race-detail-card.html', import.meta.url), 'utf8')
const classLabel = fs.readFileSync(new URL('../_includes/race-class-label.html', import.meta.url), 'utf8')
const devServer = fs.readFileSync(new URL('./dev-server.js', import.meta.url), 'utf8')
const detailNavigation = fs.readFileSync(new URL('../assets/js/race-details.js', import.meta.url), 'utf8')
const calendarNavigation = fs.readFileSync(new URL('../assets/js/race-calendar.js', import.meta.url), 'utf8')

for (const [surface, content] of Object.entries({ desktop, mobile, footer })) {
  assert.match(content, /\/corridas\//, `${surface}: link para corridas ausente`)
  assert.match(content, />Corridas</, `${surface}: rótulo Corridas ausente`)
}

assert.match(page, /permalink:\s*\/corridas\//)
assert.match(page, /id="profissional"/)
assert.match(page, /id="participar"/)
assert.match(page, /previa-corrida/)
assert.match(page, /resumo-corrida/)
assert.match(page, /data-race-filters/, 'agenda precisa oferecer filtros úteis')
assert.match(page, /data-race-filter="brazil"/, 'agenda precisa permitir destacar provas brasileiras')
assert.match(page, /data-race-filter="guide"/, 'agenda precisa permitir localizar guias completos')
assert.match(page, /event\.deepProfile\.route\.difficulty\.label/, 'cards precisam antecipar a dificuldade validada')
assert.match(page, /event\.deepProfile\.participation\.label/, 'cards precisam antecipar a situação de inscrição')
assert.match(page, /race-participant-card/, 'guias brasileiros aprofundados precisam aparecer na área de participação')
assert.match(page, /Ver inscrição, percurso e logística/, 'guia brasileiro precisa ter CTA específico')
assert.match(page, /site\.data\["race-events"\]/, 'página pública precisa consumir o snapshot oficial de corridas')
assert.match(page, /public_calendar\.today/)
assert.match(page, /id="hoje"/)
assert.match(page, /Em disputa hoje/)
assert.doesNotMatch(page, /Acontecendo agora/, 'agenda por data não pode alegar transmissão ao vivo')
assert.doesNotMatch(page, /Últimos resultados/, 'agenda recente não pode alegar resultado sem consultar classificações')
assert.match(page, /data-race-calendar/)
assert.match(page, /data-race-detail/)
assert.match(page, /\/corridas\/detalhes\/#\{\{ event\.id \}\}/)
assert.match(page, /public_calendar\.recent/)
assert.match(page, /public_calendar\.upcoming/)
assert.match(page, /countries-pt/, 'países dos cards precisam ser apresentados em português')
assert.match(page, /race-class-label\.html/, 'classes oficiais precisam receber rótulo editorial em português')
assert.doesNotMatch(page, /\{\{ event\.competitionClass \}\}/, 'classe bruta em inglês não deve aparecer diretamente na agenda')
assert.doesNotMatch(page, /href="\{\{ event\.source\.officialUrl \}\}"/, 'cards da agenda não devem expulsar o leitor do blog')
assert.match(details, /permalink:\s*\/corridas\/detalhes\//)
assert.match(details, /race-detail-card\.html/)
assert.match(detailCard, /Resultados, vencedores e classificação não são afirmados/)
assert.match(detailCard, /event\.source\.officialUrl/, 'fonte oficial precisa continuar acessível como comprovação secundária')
assert.match(detailCard, /event\.source\.discoveryUrl/, 'registro brasileiro de descoberta precisa permanecer rastreável')
assert.match(detailCard, /discovery-plus-organizer/, 'ficha brasileira precisa explicar a validação em duas fontes')
assert.match(detailCard, /O que foi validado/)
assert.match(detailCard, /Percurso, dificuldade e participação/, 'ficha precisa apresentar aprofundamento validado quando disponível')
assert.match(detailCard, /deep\.route\.totalDistanceKm/, 'ficha aprofundada precisa exibir quilometragem total')
assert.match(detailCard, /deep\.participation\.description/, 'ficha aprofundada precisa explicar como participar')
assert.match(detailCard, /deep\.route\.stages/, 'ficha aprofundada precisa apresentar o percurso por etapas')
assert.match(detailCard, /Hoje é dia de descanso/, 'ficha aprofundada precisa distinguir descanso de etapa')
assert.doesNotMatch(detailCard, /stage\.date \| date:/, 'datas canônicas não podem sofrer deslocamento de fuso no Liquid')
assert.match(detailCard, /Não completamos lacunas por estimativa/, 'ausência de fonte aprofundada precisa permanecer fail-closed')
assert.match(detailCard, /countries-pt/)
assert.ok(detailCard.indexOf('contains "CRTP"') < detailCard.indexOf('contains ".Pro"'), 'critério profissional precisa ser classificado antes da regra ProSeries')
for (const label of ['Prova brasileira de MTB', 'WorldTour feminino', 'Critério profissional', 'Copa do Mundo UCI', 'Prova por etapas · classe 1']) assert.match(classLabel, new RegExp(label))
assert.doesNotMatch(page, /em preparação/i, 'página pronta não pode continuar exibindo estado genérico de preparação')
assert.match(devServer, /\["\/corridas\/", await renderPage\("corridas\.md", "\/corridas\/"\)\]/, 'prévia local precisa renderizar a página de corridas')
assert.match(devServer, /\["\/corridas\/detalhes\/", await renderPage\("corridas-detalhes\.md", "\/corridas\/detalhes\/"\)\]/, 'prévia local precisa renderizar detalhes das corridas')
assert.match(devServer, /"race-events": JSON\.parse/, 'prévia local precisa carregar os dados do calendário oficial')
assert.match(details, /assets\/js\/race-details\.js/, 'página de detalhes precisa carregar navegação por âncora')
assert.match(detailNavigation, /scrollIntoView/, 'âncora precisa revelar a ficha selecionada')
assert.match(detailNavigation, /focus\(\{ preventScroll: true \}\)/, 'ficha selecionada precisa receber foco acessível')
assert.match(detailNavigation, /card\.hidden = card !== target/, 'detalhes precisam exibir apenas a corrida selecionada')
assert.match(detailNavigation, /section\.hidden = section !== selectedSection/, 'seções não relacionadas não devem alongar a ficha selecionada')
assert.match(detailNavigation, /pageshow/, 'restauração pelo histórico precisa reposicionar a ficha')
assert.match(calendarNavigation, /aria-pressed/, 'filtro precisa comunicar o estado para tecnologias assistivas')
assert.match(calendarNavigation, /item\.hidden = !show/, 'filtro precisa controlar a lista sem nova navegação')

console.log('Navegação e página pública de corridas validadas em desktop, mobile e rodapé.')
